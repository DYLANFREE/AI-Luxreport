function openImageViewer(src,alt,mode){
  const dialog=el('image-viewer');
  const image=el('viewer-image');
  const scroll=el('viewer-scroll');
  el('viewer-heading').textContent=alt;
  image.onload=()=>{
    const widthLimit=mode==='board'?780:1440;
    viewerBaseWidth=Math.max(260,Math.min(image.naturalWidth,widthLimit,scroll.clientWidth-32));
    viewerZoom=1;
    applyImageZoom();
    scroll.scrollTo({left:0,top:0});
  };
  image.src=src;
  image.alt=alt;
  if(!dialog.open)dialog.showModal();
  if(image.complete&&image.naturalWidth)image.onload();
}

function applyImageZoom(){
  el('viewer-image').style.width=Math.round(viewerBaseWidth*viewerZoom)+'px';
}

function changeImageZoom(delta){
  const scroll=el('viewer-scroll');
  const x=(scroll.scrollLeft+scroll.clientWidth/2)/Math.max(scroll.scrollWidth,1);
  const y=(scroll.scrollTop+scroll.clientHeight/2)/Math.max(scroll.scrollHeight,1);
  viewerZoom=Math.max(.5,Math.min(3,viewerZoom+delta));
  applyImageZoom();
  requestAnimationFrame(()=>{
    scroll.scrollLeft=x*scroll.scrollWidth-scroll.clientWidth/2;
    scroll.scrollTop=y*scroll.scrollHeight-scroll.clientHeight/2;
  });
}

function resetImageZoom(){
  viewerZoom=1;
  applyImageZoom();
  el('viewer-scroll').scrollTo({left:0,top:0,behavior:'smooth'});
}

